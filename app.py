def detect_fallback(text: str) -> str:
    normalized_text = normalize(text)

    for keyword in MANAGER_KEYWORDS:
        if keyword in normalized_text:
            return MANAGER_REPLY

    for keyword in HR_KEYWORDS:
        if keyword in normalized_text:
            return HR_REPLY

    return HR_REPLY



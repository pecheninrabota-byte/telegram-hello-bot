class MessageIn(BaseModel):
    session_id: str | None = None
    text: str | None = None
    message: str | None = None


def make_response(reply, quick_replies, state):
    return {
        "reply": reply,
        "quick_replies": quick_replies,
        "state": state
    }


def get_session(session_id):
    if session_id not in sessions:
        sessions[session_id] = {
            "session_id": session_id,
            "name": "",
            "state": STATE_WAIT_NAME,
            "current_section": None,
            "navigation_stack": []
        }
    return sessions[session_id]


def normalize(text):
    return re.sub(r"\s+", " ", text.lower()).strip()


def find_answer_by_keywords(question: str):
    question_lower = normalize(question)

    for q in ANSWERS:
        q_lower = normalize(q)
        if q_lower in question_lower or question_lower in q_lower:
            return ANSWERS[q], None

    for section, keywords in KEYWORDS.items():
        for kw in keywords:
            if kw in question_lower:
                return None, CONTACTS.get(section, CONTACTS["default"])

    return None, CONTACTS["default"]


@app.get("/")
def health():
    return {"status": "ok"}


@app.post("/api/message")
def api_message(payload: MessageIn):
    text = (payload.text or payload.message or "").strip()
    session_id = payload.session_id or "default"
    session = get_session(session_id)

    if text == "__start__":
        session["state"] = STATE_WAIT_NAME
        session["current_section"] = None
        session["navigation_stack"] = []
        return make_response(
            "Привет! Я Добрыня — твой HR-ассистент 👋\n\n"
            "Помогу тебе найти ответы по внутренним вопросам: ДМС, отгулы, обучение и другое.\n\n"
            "Давай начнем — как тебя зовут?",
            [],
            STATE_WAIT_NAME
        )

    if session["state"] == STATE_WAIT_NAME:
        session["name"] = text
        session["state"] = STATE_IDLE
        session["current_section"] = None
        session["navigation_stack"] = []
        return make_response(
            f"{text}, выбери тему 👇",
            MAIN_MENU,
            STATE_IDLE
        )

    if normalize(text) in SMALL_TALK:
        if session["current_section"]:
            return make_response(
                "Продолжим 👇",
                SUB_MENUS.get(session["current_section"], MAIN_MENU),
                STATE_IDLE
            )
        return make_response("Давай посмотрим 👇", MAIN_MENU, STATE_IDLE)

    if text == "Назад":
        if session["navigation_stack"]:
            prev_section = session["navigation_stack"].pop()
            session["current_section"] = prev_section
            return make_response(
                "Выбери вопрос 👇" if prev_section in SUB_MENUS else "Выбери тему 👇",
                SUB_MENUS.get(prev_section, MAIN_MENU),
                STATE_IDLE
            )

        session["current_section"] = None
        session["state"] = STATE_IDLE
        return make_response("Выбери тему 👇", MAIN_MENU, STATE_IDLE)

    if text in MAIN_MENU:
        if text == "Не нашёл ответ":
            session["state"] = STATE_FREE_INPUT
            return make_response(
                SECTION_DESCRIPTIONS["Не нашёл ответ"] + "\n\nМожешь написать: как накопить бонусы, что такое HighPer, где найти номер полиса и т.д.",
                [],
                STATE_FREE_INPUT
            )

        session["state"] = STATE_IDLE
        session["current_section"] = text
        session["navigation_stack"] = []
        desc = SECTION_DESCRIPTIONS.get(text, "")
        reply = f"{desc}\n\nВыбери вопрос 👇" if desc else "Выбери вопрос 👇"
        return make_response(reply, SUB_MENUS.get(text, []), STATE_IDLE)

    if text in ["Физическое благополучие", "Эмоциональное благополучие", "Финансовое благополучие", "Зоопарк"]:
        if session["current_section"]:
            session["navigation_stack"].append(session["current_section"])
        session["current_section"] = text
        return make_response("Выбери вопрос 👇", SUB_MENUS.get(text, []), STATE_IDLE)

    if session["state"] == STATE_FREE_INPUT:
        answer, contact = find_answer_by_keywords(text)
        session["state"] = STATE_IDLE

        if answer:
            if session["current_section"]:
                return make_response(
                    answer,
                    SUB_MENUS.get(session["current_section"], MAIN_MENU),
                    STATE_IDLE
                )
            return make_response(answer, MAIN_MENU, STATE_IDLE)

        reply = (
            "Не смог найти точный ответ на твой вопрос 😔\n\n"
            f"Но я знаю, кто поможет: {contact}\n\n"
            "Выбери тему из меню 👇"
        )

        if session["current_section"]:
            return make_response(
                reply,
                SUB_MENUS.get(session["current_section"], MAIN_MENU),
                STATE_IDLE
            )
        return make_response(reply, MAIN_MENU, STATE_IDLE)

    if text in ANSWERS:
        if session["current_section"]:
            return make_response(
                ANSWERS[text],
                SUB_MENUS.get(session["current_section"], MAIN_MENU),
                STATE_IDLE
            )
        return make_response(ANSWERS[text], MAIN_MENU, STATE_IDLE)

    return make_response(
        "Пока не понял вопрос 🤔 Попробуй выбрать из меню 👇",
        SUB_MENUS.get(session["current_section"], MAIN_MENU) if session["current_section"] else MAIN_MENU,
        STATE_IDLE
    )
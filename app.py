@app.get("/")
def root() -> Dict[str, str]:
    return {"status": "ok"}


@app.post("/api/message")
def api_message(payload: MessageIn) -> Dict[str, Any]:
    session_id = payload.session_id.strip()
    text = payload.text.strip()
    session = get_session(session_id)
    session["updated_at"] = now_str()

    if not text:
        reply = "Напиши, пожалуйста, сообщение, и я постараюсь помочь."
        quick_replies = MAIN_MENU if session["dialog_step"] == STATE_IDLE else []
        log_to_sheets(session, text, reply, False, "empty", session["dialog_step"])
        return make_response(reply, quick_replies, session["dialog_step"])

    if text == "__start__":
        reset_session(session)
        reply = """Привет!

Я СиЭс — HR-ассистент компании CS Medica.

Я могу помочь:
• пройти адаптацию
• найти инструкции
• разобраться с курсами
• подсказать, к кому обратиться

Для начала давай познакомимся.

Как я могу к тебе обращаться?"""
        log_to_sheets(session, text, reply, False, "start", STATE_WAIT_NAME)
        return make_response(reply, [], STATE_WAIT_NAME)

    if session["dialog_step"] == STATE_WAIT_NAME:
        session["name"] = text
        session["dialog_step"] = STATE_WAIT_DEPARTMENT
        reply = f"{text}, приятно познакомиться.\n\nВ каком направлении ты работаешь?"
        log_to_sheets(session, text, reply, False, "onboarding_name", STATE_WAIT_DEPARTMENT)
        return make_response(reply, DEPARTMENTS, STATE_WAIT_DEPARTMENT)

    if session["dialog_step"] == STATE_WAIT_DEPARTMENT:
        session["department"] = text
        session["dialog_step"] = STATE_WAIT_POSITION
        reply = "Понял! Теперь напиши, пожалуйста, свою должность как в оффере."
        log_to_sheets(session, text, reply, False, "onboarding_department", STATE_WAIT_POSITION)
        return make_response(reply, [], STATE_WAIT_POSITION)

    if session["dialog_step"] == STATE_WAIT_POSITION:
        session["position"] = text
        session["dialog_step"] = STATE_IDLE
        reply = """Отлично!

Теперь я смогу помогать тебе с адаптацией.

Выбери раздел ниже или задай вопрос."""
        log_to_sheets(session, text, reply, False, "onboarding_position", STATE_IDLE)
        return make_response(reply, MAIN_MENU, STATE_IDLE)

    menu_response = handle_main_menu(text)
    if menu_response:
        log_to_sheets(
            session,
            text,
            menu_response["reply"],
            True,
            "menu",
            menu_response["state"],
        )
        return menu_response

    answer = search_answer(text)
    if answer:
        log_to_sheets(session, text, answer, True, "knowledge", STATE_IDLE)
        return make_response(answer, MAIN_MENU, STATE_IDLE)

    fallback_reply = detect_fallback(text)
    log_to_sheets(session, text, fallback_reply, False, "fallback", STATE_IDLE)
    return make_response(fallback_reply, MAIN_MENU, STATE_IDLE)